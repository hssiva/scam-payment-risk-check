"""Generate the SYNTHETIC training set for the risk model (seeded, deterministic).

GENERATING ASSUMPTIONS (all invented for this exercise; not real customers or real fraud data)
=============================================================================================
Population: 5000 payments, seed 42. About 15% are scams (label 1), the rest genuine (label 0).
This training set is separate from the evaluation scenarios, which are written by hand later.

Genuine payments
  - 22% go to a new payee. Typical amount ratio is about 0.9 (lognormal, sigma 0.55); 3% are
    "big purchases" with a ratio of 4-9.
  - Payee account age (new payees): 8% are 5-29 days (new small businesses), 7% are 30-89 days,
    85% are 90-4000 days. Known payees are 200-4000 days.
  - Name vs account name: 91% match, 6% close, 3% mismatch.
  - 3% are on an active call, 0.3% have a remote-access tool, 7% use a new device.

Scam payments are a mix of patterns (weights in brackets), each with its own tendencies:
  - impersonation of a bank or police (35%): new payee, amount ~2.5x typical, young payee
    account, customer on an active call (85%), sometimes remote access.
  - investment scam (25%): new payee, amount ~4x typical, very young payee account.
  - remote-access / tech support (15%): remote-access tool (85%) and on a call (60%).
  - romance (15%): new payee, amount ~2.2x typical, name often mismatched, rarely on a call.
  - invoice redirection (10%): new payee with changed bank details, close or mismatched name,
    otherwise ordinary-looking amount and session.
  - 10% of scams are "coached": the victim's payment looks like a genuine one, so no model can
    catch them from these features. This keeps the metrics honest (recall cannot reach 100%).

Usage:
    python scripts/generate_training_data.py [--out PATH] [--seed N] [--count N]
"""

from __future__ import annotations

import argparse
import csv
import io
import math
import random
from dataclasses import dataclass
from pathlib import Path

SEED = 42
COUNT = 5000
SCAM_SHARE = 0.15
COACHED_SHARE = 0.10
DEFAULT_OUT = Path(__file__).resolve().parents[1] / "sample-data" / "training" / "training_data.csv"

NOTE = (
    "# SYNTHETIC - not real payments or customers. Generated by "
    "scripts/generate_training_data.py (seed {seed}, {count} rows). Do not edit by hand."
)
COLUMNS = (
    "new_payee",
    "amount_ratio",
    "payee_account_age_days",
    "name_match",
    "on_active_call",
    "remote_access_detected",
    "new_device",
    "pattern",
    "label",
)
NAME_MATCHES = ("MATCH", "CLOSE", "MISMATCH")
KNOWN_PAYEE_AGE = (200, 4000)


@dataclass(frozen=True)
class Pattern:
    name: str
    new_payee_p: float
    ratio_mu: float  # lognormal parameters of amount_ratio
    ratio_sigma: float
    age_buckets: tuple[tuple[float, int, int], ...]  # (weight, min_days, max_days), new payees
    name_weights: tuple[float, float, float]  # MATCH, CLOSE, MISMATCH
    call_p: float
    remote_p: float
    device_p: float
    big_ratio_p: float = 0.0  # chance of a "big purchase" ratio of 4-9


GENUINE = Pattern(
    "genuine", 0.22, -0.1, 0.55,
    ((0.08, 5, 29), (0.07, 30, 89), (0.85, 90, 4000)),
    (0.91, 0.06, 0.03), 0.03, 0.003, 0.07, big_ratio_p=0.03,
)  # fmt: skip

# (pattern, weight)
SCAM_PATTERNS: tuple[tuple[Pattern, float], ...] = (
    (
        Pattern(
            "impersonation", 0.95, 0.9, 0.7,
            ((0.45, 1, 29), (0.35, 30, 365), (0.20, 366, 3000)),
            (0.50, 0.15, 0.35), 0.85, 0.10, 0.25,
        ),
        0.35,
    ),
    (
        Pattern(
            "investment", 0.97, 1.4, 0.8,
            ((0.55, 1, 29), (0.30, 30, 180), (0.15, 181, 2000)),
            (0.50, 0.20, 0.30), 0.15, 0.05, 0.20,
        ),
        0.25,
    ),
    (
        Pattern(
            "remote_access", 0.90, 0.6, 0.7,
            ((0.35, 1, 29), (0.35, 30, 365), (0.30, 366, 3000)),
            (0.60, 0.10, 0.30), 0.60, 0.85, 0.35,
        ),
        0.15,
    ),
    (
        Pattern(
            "romance", 0.90, 0.8, 0.8,
            ((0.30, 1, 29), (0.40, 30, 365), (0.30, 366, 3000)),
            (0.45, 0.15, 0.40), 0.05, 0.02, 0.10,
        ),
        0.15,
    ),
    (
        Pattern(
            "invoice_redirection", 0.90, 0.5, 0.6,
            ((0.30, 1, 29), (0.40, 30, 400), (0.30, 401, 3000)),
            (0.20, 0.40, 0.40), 0.03, 0.01, 0.05,
        ),
        0.10,
    ),
)  # fmt: skip


def draw_ratio(rng: random.Random, pattern: Pattern) -> float:
    if rng.random() < pattern.big_ratio_p:
        return rng.uniform(4.0, 9.0)
    ratio = math.exp(rng.gauss(pattern.ratio_mu, pattern.ratio_sigma))
    return min(max(ratio, 0.01), 50.0)


def draw_age(rng: random.Random, buckets: tuple[tuple[float, int, int], ...]) -> int:
    _, low, high = rng.choices(buckets, weights=[b[0] for b in buckets])[0]
    return rng.randint(low, high)


def draw_payment(rng: random.Random, pattern: Pattern) -> dict[str, object]:
    new_payee = rng.random() < pattern.new_payee_p
    ratio = draw_ratio(rng, pattern)
    age = draw_age(rng, pattern.age_buckets) if new_payee else rng.randint(*KNOWN_PAYEE_AGE)
    name_match = rng.choices(NAME_MATCHES, weights=pattern.name_weights)[0]
    return {
        "new_payee": int(new_payee),
        "amount_ratio": f"{ratio:.4f}",
        "payee_account_age_days": age,
        "name_match": name_match,
        "on_active_call": int(rng.random() < pattern.call_p),
        "remote_access_detected": int(rng.random() < pattern.remote_p),
        "new_device": int(rng.random() < pattern.device_p),
    }


def pick_pattern(rng: random.Random, is_scam: bool) -> tuple[Pattern, str]:
    if not is_scam:
        return GENUINE, GENUINE.name
    if rng.random() < COACHED_SHARE:
        return GENUINE, "coached_scam"
    patterns = [p for p, _ in SCAM_PATTERNS]
    chosen = rng.choices(patterns, weights=[w for _, w in SCAM_PATTERNS])[0]
    return chosen, chosen.name


def generate_rows(count: int = COUNT, seed: int = SEED) -> list[dict[str, object]]:
    rng = random.Random(seed)
    rows: list[dict[str, object]] = []
    for _ in range(count):
        is_scam = rng.random() < SCAM_SHARE
        pattern, label_name = pick_pattern(rng, is_scam)
        row = draw_payment(rng, pattern)
        row["pattern"] = label_name
        row["label"] = int(is_scam)
        rows.append(row)
    return rows


def render(rows: list[dict[str, object]], seed: int = SEED) -> str:
    buffer = io.StringIO()
    buffer.write(NOTE.format(seed=seed, count=len(rows)) + "\n")
    writer = csv.DictWriter(buffer, fieldnames=COLUMNS, lineterminator="\n")
    writer.writeheader()
    writer.writerows(rows)
    return buffer.getvalue()


def generate(out: Path, count: int = COUNT, seed: int = SEED) -> Path:
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render(generate_rows(count, seed), seed), encoding="utf-8")
    return out


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate SYNTHETIC training data.")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--seed", type=int, default=SEED)
    parser.add_argument("--count", type=int, default=COUNT)
    args = parser.parse_args()
    print(f"wrote {generate(args.out, args.count, args.seed)}")


if __name__ == "__main__":
    main()
